"use client";

import React, { useState } from "react";
import jsPDF from "jspdf";
import { Download, FileText, FileSignature } from "lucide-react";
import { motion } from "framer-motion";
import { NotoSansBengaliBase64 } from "@/lib/fonts/NotoSansBengali";

export default function PDFGeneratorPage() {
  const [text, setText] = useState("");
  const [isGenerating, setIsGenerating] = useState(false);

  const handleGeneratePDF = async () => {
    if (!text.trim()) return;

    setIsGenerating(true);

    try {
      // 1. Initialize jsPDF
      const doc = new jsPDF();

      // 2. Add Bengali Font
      doc.addFileToVFS("NotoSansBengali.ttf", NotoSansBengaliBase64);
      doc.addFont("NotoSansBengali.ttf", "NotoSansBengali", "normal");

      const pageWidth = doc.internal.pageSize.getWidth();
      const pageHeight = doc.internal.pageSize.getHeight();

      // 3. Draw Header
      // Brand color: #1dbf73 -> RGB(29, 191, 115)
      doc.setFillColor(29, 191, 115);
      doc.rect(0, 0, pageWidth, 25, "F");

      doc.setTextColor(255, 255, 255);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(18);
      doc.text("ATTENDANCE SYSTEM", pageWidth / 2, 16, { align: "center" });

      // 4. Draw Body Content
      doc.setTextColor(30, 41, 59); // slate-800
      doc.setFont("NotoSansBengali", "normal");
      doc.setFontSize(12);

      // Margin setup
      const margin = 15;
      const textWidth = pageWidth - margin * 2;
      const splitText = doc.splitTextToSize(text, textWidth);
      
      doc.text(splitText, margin, 38);

      // 5. Draw Footer across all pages
      const pageCount = doc.internal.getNumberOfPages();
      for (let i = 1; i <= pageCount; i++) {
        doc.setPage(i);
        // Footer background
        doc.setFillColor(241, 245, 249); // slate-100
        doc.rect(0, pageHeight - 15, pageWidth, 15, "F");
        
        doc.setTextColor(100, 116, 139); // slate-500
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        doc.text("Generated by Attendance System", margin, pageHeight - 6);
        doc.text(`Page ${i} of ${pageCount}`, pageWidth - margin, pageHeight - 6, { align: "right" });
      }

      // 6. Save the PDF
      doc.save("Generated_Document.pdf");
    } catch (error) {
      console.error("Error generating PDF:", error);
    } finally {
      setIsGenerating(false);
    }
  };

  return (
    <div className="min-h-screen bg-[var(--background)] p-4 md:p-8 flex items-center justify-center">
      <motion.div 
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.5 }}
        className="w-full max-w-4xl"
      >
        <div className="glass-panel rounded-2xl overflow-hidden flex flex-col md:flex-row shadow-xl">
          
          {/* Left Side: Information & Branding */}
          <div className="bg-gradient-to-br from-[#1dbf73] to-[#108a50] p-8 md:w-2/5 text-white flex flex-col justify-between relative overflow-hidden">
            {/* Decorative background elements */}
            <div className="absolute top-[-10%] right-[-10%] w-64 h-64 rounded-full bg-white opacity-10 blur-3xl"></div>
            <div className="absolute bottom-[-10%] left-[-10%] w-48 h-48 rounded-full bg-black opacity-10 blur-2xl"></div>

            <div className="relative z-10">
              <div className="bg-white/20 p-3 rounded-xl inline-block mb-6 backdrop-blur-sm">
                <FileSignature size={32} className="text-white" />
              </div>
              <h1 className="text-3xl font-bold mb-4 tracking-tight">PDF Generator</h1>
              <p className="text-white/80 leading-relaxed">
                Create beautifully branded PDF documents instantly. Simply type or paste your Bengali content, and we&apos;ll format it with our official headers and footers.
              </p>
            </div>

            <div className="mt-12 relative z-10">
              <div className="flex items-center space-x-3 text-sm text-white/90">
                <div className="w-8 h-8 rounded-full bg-white/20 flex items-center justify-center backdrop-blur-sm">
                  <FileText size={16} />
                </div>
                <span>Supports Noto Sans Bengali font</span>
              </div>
            </div>
          </div>

          {/* Right Side: Input Form */}
          <div className="p-8 md:w-3/5 bg-white">
            <h2 className="text-xl font-semibold text-slate-800 mb-6">Document Content</h2>
            
            <div className="flex flex-col h-full space-y-6">
              <div className="flex-grow">
                <label htmlFor="content" className="sr-only">Content</label>
                <textarea
                  id="content"
                  className="w-full h-64 md:h-80 p-4 rounded-xl border border-slate-200 bg-slate-50 text-slate-800 placeholder-slate-400 focus:outline-none focus:ring-2 focus:ring-[#1dbf73]/50 focus:border-[#1dbf73] transition-all resize-none"
                  placeholder="এখানে আপনার টেক্সট লিখুন..."
                  value={text}
                  onChange={(e) => setText(e.target.value)}
                  style={{ fontFamily: "'Noto Sans Bengali', sans-serif" }}
                />
              </div>

              <div className="flex justify-end pt-2">
                <button
                  onClick={handleGeneratePDF}
                  disabled={!text.trim() || isGenerating}
                  className={`flex items-center space-x-2 px-6 py-3 rounded-xl font-semibold transition-all shadow-lg ${
                    !text.trim() || isGenerating
                      ? "bg-slate-200 text-slate-400 cursor-not-allowed shadow-none"
                      : "premium-gradient text-white hover:-translate-y-1 hover:shadow-[#1dbf73]/40"
                  }`}
                >
                  {isGenerating ? (
                    <div className="w-5 h-5 border-2 border-white/30 border-t-white rounded-full animate-spin" />
                  ) : (
                    <Download size={20} />
                  )}
                  <span>{isGenerating ? "Generating..." : "Download PDF"}</span>
                </button>
              </div>
            </div>
          </div>

        </div>
      </motion.div>
    </div>
  );
}
